const LANG_KEY = "atelier-lang";
const SUPPORTED = /** @type {const} */ (["ua", "de"]);

/** @type {"ua" | "de"} */
let currentLang = "ua";

/** @param {"ua" | "de"} lang */
function t(lang, key) {
	const entry = content[key];
	if (!entry) return "";
	const val = entry[lang] ?? entry.ua ?? "";
	return typeof val === "string" ? val : "";
}

/** @param {string} tpl @param {string | number} n */
function formatTpl(tpl, n) {
	return tpl.replace("%s", String(n));
}

function readStoredLang() {
	try {
		const raw = localStorage.getItem(LANG_KEY);
		if (raw === "ua" || raw === "de") return raw;
	} catch {
		/* ignore */
	}
	const nav = (navigator.language || "").toLowerCase();
	if (nav.startsWith("de")) return "de";
	return "ua";
}

/** @param {"ua" | "de"} lang */
function applyLanguage(lang) {
	if (!SUPPORTED.includes(lang)) lang = "ua";
	currentLang = lang;

	document.documentElement.lang = lang === "de" ? "de" : "uk";

	const title = t(lang, "meta_title");
	if (title) document.title = title;

	document.querySelectorAll("[data-i18n]").forEach((el) => {
		const key = el.getAttribute("data-i18n");
		if (!key) return;
		const text = t(lang, key);
		if (!text) return;
		if (text.includes("<")) {
			el.innerHTML = text;
		} else {
			el.textContent = text;
		}
	});

	document.querySelectorAll("[data-i18n-attr]").forEach((el) => {
		const spec = el.getAttribute("data-i18n-attr");
		if (!spec) return;
		const [attr, key] = spec.split("|").map((s) => s.trim());
		if (!attr || !key) return;
		const text = t(lang, key);
		if (text) el.setAttribute(attr, text);
	});

	document.querySelectorAll("[data-lang]").forEach((btn) => {
		const code = btn.getAttribute("data-lang");
		const active = code === lang;
		btn.setAttribute("aria-pressed", active ? "true" : "false");
	});

	syncContactLinks(lang);
	renderTestimonials(lang);
	syncMenuToggleAria();

	try {
		localStorage.setItem(LANG_KEY, lang);
	} catch {
		/* ignore */
	}
}

/** @param {"ua" | "de"} lang */
function syncContactLinks(lang) {
	const email = t(lang, "contact_email");
	const phone = t(lang, "contact_phone");
	const emailEl = document.querySelector("[data-contact-email]");
	const phoneEl = document.querySelector("[data-contact-phone]");
	if (emailEl && email) {
		emailEl.textContent = email;
		emailEl.setAttribute("href", `mailto:${email}`);
	}
	if (phoneEl && phone) {
		phoneEl.textContent = phone;
		const tel = phone.replace(/[^\d+]/g, "");
		phoneEl.setAttribute("href", `tel:${tel}`);
	}
}

const testimonialKeys = [
	{ quote: "testimonial_1_quote", author: "testimonial_1_author" },
	{ quote: "testimonial_2_quote", author: "testimonial_2_author" },
	// { quote: "testimonial_3_quote", author: "testimonial_3_author" },
];

let testimonialIndex = 0;

/** @param {"ua" | "de"} lang */
function renderTestimonials(lang) {
	const track = document.querySelector("[data-testimonial-track]");
	const dots = document.querySelector("[data-testimonial-dots]");
	if (!track || !dots) return;

	track.innerHTML = "";
	dots.innerHTML = "";

	testimonialKeys.forEach((item, i) => {
		const slide = document.createElement("article");
		slide.className = "testimonial__slide";
		slide.setAttribute("role", "tabpanel");
		slide.setAttribute("aria-roledescription", "slide");
		slide.setAttribute(
			"aria-label",
			formatTpl(t(lang, "testimonial_slide_aria"), i + 1),
		);

		const q = document.createElement("p");
		q.className = "testimonial__quote";
		q.textContent = t(lang, item.quote);

		const a = document.createElement("p");
		a.className = "testimonial__author";
		a.textContent = t(lang, item.author);

		slide.append(q, a);
		track.append(slide);

		const dot = document.createElement("button");
		dot.type = "button";
		dot.className = "testimonial__dot";
		dot.setAttribute("role", "tab");
		dot.setAttribute(
			"aria-selected",
			i === testimonialIndex ? "true" : "false",
		);
		dot.setAttribute(
			"aria-label",
			formatTpl(t(lang, "testimonial_slide_aria"), i + 1),
		);
		dot.addEventListener("click", () => {
			testimonialIndex = i;
			updateTestimonialTrack(false);
		});
		dots.append(dot);
	});

	if (testimonialIndex >= testimonialKeys.length) testimonialIndex = 0;
	updateTestimonialTrack(true);
}

/** @param {boolean} instant */
function updateTestimonialTrack(instant) {
	const slides = document.querySelectorAll(".testimonial__slide");
	if (!slides.length) return;

	slides.forEach((slide, i) => {
		const active = i === testimonialIndex;
		if (instant) {
			slide.style.transition = "none";
			slide.classList.toggle("is-active", active);
			requestAnimationFrame(() => {
				requestAnimationFrame(() => {
					slide.style.transition = "";
				});
			});
		} else {
			slide.classList.toggle("is-active", active);
		}
	});

	const dots = document.querySelectorAll(".testimonial__dot");
	dots.forEach((d, i) =>
		d.setAttribute("aria-selected", i === testimonialIndex ? "true" : "false"),
	);
}

function setupTestimonialControls() {
	const prev = document.querySelector("[data-testimonial-prev]");
	const next = document.querySelector("[data-testimonial-next]");
	prev?.addEventListener("click", () => {
		testimonialIndex =
			(testimonialIndex - 1 + testimonialKeys.length) % testimonialKeys.length;
		updateTestimonialTrack(false);
	});
	next?.addEventListener("click", () => {
		testimonialIndex = (testimonialIndex + 1) % testimonialKeys.length;
		updateTestimonialTrack(false);
	});
}

function setupLangToggle() {
	document.querySelectorAll("[data-lang]").forEach((btn) => {
		btn.addEventListener("click", () => {
			const code = btn.getAttribute("data-lang");
			if (code === "ua" || code === "de") applyLanguage(code);
		});
	});
}

function setupHeaderScroll() {
	const header = document.querySelector(".header");
	if (!header) return;
	const onScroll = () => {
		header.classList.toggle("is-scrolled", window.scrollY > 10);
	};
	onScroll();
	window.addEventListener("scroll", onScroll, { passive: true });
}

function setupReveal() {
	const els = document.querySelectorAll(".reveal");
	if (!els.length) return;

	const reduce = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
	if (reduce) {
		els.forEach((el) => el.classList.add("is-visible"));
		return;
	}

	const io = new IntersectionObserver(
		(entries) => {
			entries.forEach((entry) => {
				if (!entry.isIntersecting) return;
				entry.target.classList.add("is-visible");
				io.unobserve(entry.target);
			});
		},
		{ root: null, threshold: 0.12, rootMargin: "0px 0px -8% 0px" },
	);

	els.forEach((el, i) => {
		el.style.setProperty("--reveal-delay", `${Math.min(i, 6) * 45}ms`);
		io.observe(el);
	});
}

function syncMenuToggleAria() {
	const toggle = document.querySelector(".menu-toggle");
	if (!toggle) return;
	const open = toggle.getAttribute("aria-expanded") === "true";
	const key = open ? "menu_close_aria" : "menu_open_aria";
	const label = t(currentLang, key);
	if (label) toggle.setAttribute("aria-label", label);
}

function closeMobileNav() {
	const toggle = document.querySelector(".menu-toggle");
	const panel = document.getElementById("mobile-nav");
	if (!toggle || !panel) return;
	toggle.setAttribute("aria-expanded", "false");
	panel.hidden = true;
	document.body.style.overflow = "";
	syncMenuToggleAria();
}

function setupScrollToTop() {
	const link = document.querySelector("[data-scroll-top]");
	if (!link) return;

	link.addEventListener("click", (e) => {
		e.preventDefault();
		closeMobileNav();
		const reduce = window.matchMedia(
			"(prefers-reduced-motion: reduce)",
		).matches;
		window.scrollTo({ top: 0, left: 0, behavior: reduce ? "auto" : "smooth" });
		if (window.location.hash) {
			history.replaceState(
				null,
				"",
				`${window.location.pathname}${window.location.search}`,
			);
		}
	});
}

function setupMobileNav() {
	const toggle = document.querySelector(".menu-toggle");
	const panel = document.getElementById("mobile-nav");
	if (!toggle || !panel) return;

	const setOpen = (open) => {
		toggle.setAttribute("aria-expanded", open ? "true" : "false");
		panel.hidden = !open;
		document.body.style.overflow = open ? "hidden" : "";
		syncMenuToggleAria();
	};

	toggle.addEventListener("click", () => {
		const open = toggle.getAttribute("aria-expanded") === "true";
		setOpen(!open);
	});

	panel.querySelectorAll("a").forEach((a) => {
		a.addEventListener("click", () => setOpen(false));
	});

	window.addEventListener("resize", () => {
		if (window.innerWidth > 880) setOpen(false);
	});
}

